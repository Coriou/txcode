// Fork-local: Oh My Pi exposes no ACP surface for OpenRouter upstream routing
// (can1357/oh-my-pi#14876). A generated extension rewrites the request payload instead.
import type { ProviderOptionSelection } from "@t3tools/contracts";
import * as Clock from "effect/Clock";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Option from "effect/Option";
import * as Path from "effect/Path";
import { writeFileStringAtomically } from "@t3tools/shared/atomicWrite";

export const OMP_OPENROUTER_UPSTREAM_OPTION_ID = "openrouterUpstream";
export const OMP_OPENROUTER_ROUTING_ENV = "T3_OMP_ROUTING_DIR";
/** Selection value meaning "let OpenRouter route"; it never reaches the pin file. */
export const OMP_OPENROUTER_UPSTREAM_AUTO = "auto";

const ROUTING_DIR_NAME = "omp-openrouter-routing";
const PINS_DIR_NAME = "pins";
const EXTENSION_FILE_NAME = "openrouter-routing.ts";
const PIN_FILE_MAX_AGE_MS = 7 * 24 * 60 * 60 * 1_000;

export interface OmpOpenRouterRoutingPaths {
  /** Directory holding the generated extension; passed to OMP through the routing env var. */
  readonly dir: string;
  readonly pinsDir: string;
  readonly extensionPath: string;
}

export const ompOpenRouterRoutingPaths = Effect.fn("ompOpenRouterRoutingPaths")(function* (
  stateDir: string,
) {
  const path = yield* Path.Path;
  const dir = path.join(stateDir, ROUTING_DIR_NAME);
  return {
    dir,
    pinsDir: path.join(dir, PINS_DIR_NAME),
    extensionPath: path.join(dir, EXTENSION_FILE_NAME),
  } satisfies OmpOpenRouterRoutingPaths;
});

/** Comma-separated setting value to selectable OpenRouter provider slugs. */
export function openRouterUpstreamsFromSetting(
  raw: string | null | undefined,
): ReadonlyArray<string> {
  if (!raw) return [];
  const seen = new Set<string>();
  const upstreams: Array<string> = [];
  for (const entry of raw.split(",")) {
    const normalized = entry.trim().toLowerCase();
    if (normalized.length === 0 || seen.has(normalized)) continue;
    seen.add(normalized);
    upstreams.push(normalized);
  }
  return upstreams;
}

/** The pinned upstream, or undefined when the thread asks for OpenRouter's own routing. */
export function openRouterUpstreamFromSelection(
  selections: ReadonlyArray<ProviderOptionSelection> | null | undefined,
): string | undefined {
  for (const selection of selections ?? []) {
    if (selection.id !== OMP_OPENROUTER_UPSTREAM_OPTION_ID) continue;
    if (typeof selection.value !== "string") return undefined;
    const normalized = selection.value.trim().toLowerCase();
    if (normalized.length === 0 || normalized === OMP_OPENROUTER_UPSTREAM_AUTO) return undefined;
    return normalized;
  }
  return undefined;
}

/** A stored pin only counts while the instance still offers that upstream. */
export function resolvePinnedUpstream(
  selections: ReadonlyArray<ProviderOptionSelection> | null | undefined,
  configuredUpstreams: ReadonlyArray<string>,
): string | undefined {
  const upstream = openRouterUpstreamFromSelection(selections);
  return upstream !== undefined && configuredUpstreams.includes(upstream) ? upstream : undefined;
}

export function ompOpenRouterPinFileName(sessionId: string): string {
  return `${encodeURIComponent(sessionId)}.pin`;
}

/**
 * The extension OMP loads with `-e`: it rewrites OpenRouter requests whose model
 * matches the session's pin. An in-session id rotation (ctx.newSession) drops
 * the pin; T3 re-writes it on the next activation.
 */
export const OMP_OPENROUTER_ROUTING_EXTENSION_SOURCE = `// Generated by Tx Code. Regenerated on server start; edits are overwritten.
import * as fs from "node:fs";
import * as path from "node:path";

export default function txCodeOpenRouterRouting(pi) {
  const dir = process.env.${OMP_OPENROUTER_ROUTING_ENV};
  if (!dir) return;
  const pinsDir = path.join(dir, "${PINS_DIR_NAME}");

  const readPin = (ctx) => {
    const model = ctx.model;
    if (!model || model.provider !== "openrouter") return undefined;
    const sessionId = ctx.sessionManager?.getSessionId?.();
    if (!sessionId) return undefined;
    try {
      const file = path.join(pinsDir, encodeURIComponent(sessionId) + ".pin");
      const [upstream, pinnedModel] = fs.readFileSync(file, "utf8").split("\\n").map((line) => line.trim());
      if (upstream.length === 0 || pinnedModel !== model.provider + "/" + model.id) return undefined;
      return [upstream];
    } catch {
      return undefined;
    }
  };

  pi.on("before_provider_request", (event, ctx) => {
    const only = readPin(ctx);
    if (!only) return undefined;
    const payload = event.payload;
    if (!payload || typeof payload !== "object" || Array.isArray(payload)) return undefined;
    const current = payload.provider && typeof payload.provider === "object" ? payload.provider : {};
    return { ...payload, provider: { ...current, only } };
  });
}
`;

/** Pins are keyed by ACP session id, so files for long-gone sessions are garbage. */
const pruneOmpOpenRouterPins = Effect.fnUntraced(function* (paths: OmpOpenRouterRoutingPaths) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const now = yield* Clock.currentTimeMillis;
  const entries = yield* fs.readDirectory(paths.pinsDir);
  yield* Effect.forEach(
    entries,
    (entry) =>
      Effect.gen(function* () {
        if (!entry.endsWith(".pin")) return;
        const fullPath = path.join(paths.pinsDir, entry);
        const modifiedAt = Option.getOrNull((yield* fs.stat(fullPath)).mtime);
        if (modifiedAt !== null && now - modifiedAt.getTime() <= PIN_FILE_MAX_AGE_MS) return;
        yield* fs.remove(fullPath).pipe(Effect.ignore);
      }),
    { discard: true },
  );
});

export const prepareOmpOpenRouterRouting = Effect.fn("prepareOmpOpenRouterRouting")(function* (
  paths: OmpOpenRouterRoutingPaths,
) {
  const fs = yield* FileSystem.FileSystem;
  yield* fs.makeDirectory(paths.pinsDir, { recursive: true });
  yield* writeFileStringAtomically({
    filePath: paths.extensionPath,
    contents: OMP_OPENROUTER_ROUTING_EXTENSION_SOURCE,
  });
  yield* pruneOmpOpenRouterPins(paths).pipe(
    Effect.catchCause((cause) =>
      Effect.logWarning("Failed to prune Oh My Pi OpenRouter pin files", { cause }),
    ),
  );
});

export const writeOmpOpenRouterPin = Effect.fn("writeOmpOpenRouterPin")(function* (input: {
  readonly paths: OmpOpenRouterRoutingPaths;
  readonly sessionId: string;
  /** OMP model selector (`provider/id`) the pin applies to. */
  readonly model: string;
  readonly upstream: string | undefined;
}) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  yield* fs.makeDirectory(input.paths.pinsDir, { recursive: true });
  const filePath = path.join(input.paths.pinsDir, ompOpenRouterPinFileName(input.sessionId));
  if (input.upstream === undefined) {
    yield* fs.remove(filePath).pipe(Effect.ignore);
    return;
  }
  yield* writeFileStringAtomically({
    filePath,
    contents: `${input.upstream}\n${input.model}\n`,
  });
});
